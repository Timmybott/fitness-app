"""
Builds the reference_foods migration from the Swiss Food Composition Database (Schweizer Nährwertdatenbank,
Federal Food Safety and Veterinary Office FSVO/BLV, https://naehrwertdaten.ch). Free to use, also
commercially, with attribution ("Quelle: Schweizer Nährwertdatenbank").

  python import_swiss_foods.py Schweizer_Nahrwertdatenbank.xlsx > ../migrations/008_reference_foods.sql

Only the "generic foods" sheet is used. The xlsx is read with the standard library (it is a zip of XML).
"""

import re
import sys
import xml.etree.ElementTree as ET
import zipfile

NS = '{http://schemas.openxmlformats.org/spreadsheetml/2006/main}'
SHEET = 'xl/worksheets/sheet1.xml'
HEADER_ROW = 2  # rows 0-1 are title and version note

# Column titles in the sheet -> our fields.
COLUMNS = {
    'ID': 'id',
    'Name': 'name',
    'Synonyme': 'synonyms',
    'Kategorie': 'category',
    'Bezugseinheit': 'unit',
    'Energie, Kalorien (kcal)': 'kcal',
    'Protein (g)': 'protein',
    'Kohlenhydrate, verfügbar (g)': 'carbs',
    'Fett, total (g)': 'fat',
    'Zucker (g)': 'sugar',
    'Nahrungsfasern (g)': 'fiber',
    'Salz (NaCl) (g)': 'salt',
}


def read_rows(path):
    z = zipfile.ZipFile(path)
    shared = [''.join(t.text or '' for t in si.iter(NS + 't')) for si in ET.fromstring(z.read('xl/sharedStrings.xml')).findall(NS + 'si')]
    rows = []
    for r in ET.fromstring(z.read(SHEET)).iter(NS + 'row'):
        row = {}
        for c in r.findall(NS + 'c'):
            col = re.match(r'[A-Z]+', c.get('r')).group(0)
            v = c.find(NS + 'v')
            if v is not None:
                row[col] = shared[int(v.text)] if c.get('t') == 's' else v.text
        rows.append(row)
    return rows


def number(v):
    """'k.A.' (no data) and empty cells become None; rounds float noise like 74.099999999999994."""
    try:
        return round(float(v), 2)
    except (TypeError, ValueError):
        return None


def sql(v):
    if v is None:
        return 'NULL'
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def main(path):
    rows = read_rows(path)
    header = {col: COLUMNS[title] for col, title in rows[HEADER_ROW].items() if title in COLUMNS}
    foods = []
    for r in rows[HEADER_ROW + 1:]:
        f = {field: r.get(col) for col, field in header.items()}
        if not f.get('id') or not f.get('name') or number(f.get('kcal')) is None:
            continue
        foods.append({
            'id': int(f['id']),
            'name': f['name'].strip(),
            'synonyms': (f.get('synonyms') or '').strip() or None,
            'category': (f.get('category') or '').strip() or None,
            # Drinks are given per 100 ml; the app logs them in ml (1 ml ≈ 1 g).
            'unit': 'ml' if 'ml' in (f.get('unit') or '') else 'g',
            'kcal': number(f['kcal']),
            'protein': number(f.get('protein')) or 0,
            'carbs': number(f.get('carbs')) or 0,
            'fat': number(f.get('fat')) or 0,
            'sugar': number(f.get('sugar')),
            'fiber': number(f.get('fiber')),
            'salt': number(f.get('salt')),
        })

    cols = ['id', 'name', 'synonyms', 'category', 'unit', 'kcal', 'protein', 'carbs', 'fat', 'sugar', 'fiber', 'salt']
    out = [
        '-- Generated by tools/import_swiss_foods.py from the Swiss Food Composition Database',
        '-- (Schweizer Nährwertdatenbank, FSVO/BLV, naehrwertdaten.ch). Values per 100 g or 100 ml.',
        'CREATE TABLE reference_foods (',
        '  id INTEGER PRIMARY KEY,',
        '  name TEXT NOT NULL,',
        '  synonyms TEXT,',
        '  category TEXT,',
        "  unit TEXT NOT NULL CHECK (unit IN ('g', 'ml')),",
        '  kcal NUMERIC NOT NULL,',
        '  protein NUMERIC NOT NULL,',
        '  carbs NUMERIC NOT NULL,',
        '  fat NUMERIC NOT NULL,',
        '  sugar NUMERIC,',
        '  fiber NUMERIC,',
        '  salt NUMERIC',
        ');',
        '',
        f'INSERT INTO reference_foods ({", ".join(cols)}) VALUES',
    ]
    out.append(',\n'.join('(' + ', '.join(sql(f[c]) for c in cols) + ')' for f in foods) + ';')
    sys.stdout.reconfigure(encoding='utf-8')
    print('\n'.join(out))
    print(f'{len(foods)} foods', file=sys.stderr)


if __name__ == '__main__':
    main(sys.argv[1])
